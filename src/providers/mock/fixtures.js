function generateTestcases({ prompt }) {
  const requirementIds = idsIn(prompt, /\bREQ-\d{3,}\b/g);
  const attentionAreaIds = idsIn(prompt, /\bAA-\d{3,}\b/g);

  const testcases = (requirementIds.length > 0 ? requirementIds : ['REQ-000']).flatMap(
    (requirementId, index) => {
      const number = (offset) => `TC-${String(index * 2 + offset).padStart(3, '0')}`;
      return [
        {
          testcase_id: number(1),
          scenario: `Mock positive scenario for ${requirementId}.`,
          steps: ['Mock step: prepare the precondition.', 'Mock step: perform the action.'],
          expected_result: `Mock expected result for ${requirementId}.`,
          requirement_ref: requirementId,
          review_required: false,
          review_reason: null,
          attention_area_ids: [],
        },
        {
          testcase_id: number(2),
          scenario: `Mock negative scenario for ${requirementId}.`,
          steps: ['Mock step: prepare an invalid input.', 'Mock step: perform the action.'],
          expected_result: `Mock rejection result for ${requirementId}.`,
          requirement_ref: requirementId,
          review_required: attentionAreaIds.length > 0,
          review_reason:
            attentionAreaIds.length > 0 ? 'Mock reason: touches a listed attention area.' : null,
          attention_area_ids: attentionAreaIds,
        },
      ];
    }
  );

  return { testcases };
}

