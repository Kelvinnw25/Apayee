/**
 * Illustrative answers that demonstrate the protocol. The text is obviously
 * placeholder content and reflects no real document or business rule.
 *
 * Like any stateless model, generate_testcases can only know what is in its prompt.
 * It reads requirement and attention-area ids back out of the prompt text, which
 * makes context handoff observable: ids appear in the output only if the client
 * actually sent them.
 */
function idsIn(prompt, pattern) {
  return [...new Set(prompt.match(pattern) ?? [])];
}

